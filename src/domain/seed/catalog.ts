export function buildCatalog(mkId: () => string): { sections: CatalogSection[]; items: CatalogItem[] } {
  const sections: CatalogSection[] = SEED_SECTIONS.map((s, i) => ({
    id: `sec-${s.code}`,
    code: s.code,
    title: s.title,
    stage: s.stage,
    order: i,
  }));

  const items: CatalogItem[] = [];
  for (const section of sections) {
    const rows = SEED_ITEMS[section.code] ?? [];
    for (const [code, title, unit, kind, price, cost, qtyBasis, qtyFactor, companions, requires] of rows) {
      items.push({
        id: mkId(),
        sectionId: section.id,
        code,
        title,
        unit,
        kind,
        price,
        cost,
        qtyBasis,
        qtyFactor: qtyFactor ?? 1,
        companions: companions ?? [],
        requires: requires ?? [],
        active: true,
      });
    }
  }
  return { sections, items };
}
